import Foundation

/// Interface language. Every visible string is written in English in the source and
/// looked up in one dictionary per language here, so adding Russian means adding a
/// `russian` dictionary and a case below. Model keys, identifiers, database values and
/// backup folder names stay English; only what is shown to the user is translated.
public enum Language: Sendable {
    case english, uzbek

    public static let current: Language = .uzbek

    var table: [String: String] {
        switch self {
        case .english: [:]
        case .uzbek: Localization.uzbek
        }
    }

    public var locale: Locale {
        switch self {
        case .english: Locale(identifier: "en_US")
        case .uzbek: Locale(identifier: "uz_Latn_UZ")
        }
    }
}

/// Translates an English source string into the current language. `%@` takes the next
/// argument and `%1$@`, `%2$@` take one by position; any other `%` is kept as is.
/// A missing translation falls back to the English text.
public func tr(_ key: String, _ arguments: CustomStringConvertible...) -> String {
    Localization.format(Language.current.table[key] ?? key, arguments.map(\.description))
}

public enum Localization {
    static func format(_ template: String, _ arguments: [String]) -> String {
        guard !arguments.isEmpty, template.contains("%") else { return template }
        var result = ""
        var next = 0
        var rest = Substring(template)
        while let percent = rest.firstIndex(of: "%") {
            result += rest[..<percent]
            let after = rest[rest.index(after: percent)...]
            if after.hasPrefix("@") {
                result += next < arguments.count ? arguments[next] : ""
                next += 1
                rest = after.dropFirst()
            } else if let dollar = after.firstIndex(of: "$"), let position = Int(after[..<dollar]),
                      after[after.index(after: dollar)...].hasPrefix("@") {
                result += arguments.indices.contains(position - 1) ? arguments[position - 1] : ""
                rest = after[after.index(dollar, offsetBy: 2)...]
            } else {
                result += "%"
                rest = after
            }
        }
        return result + rest
    }

